module Eval_Dam_mod
!
!  Evaluates the results of the cascade calculations
!
!  Used Modules:
!  ============
!
   use Const_mod,          only: INT4, REAL8, &
                                 ZERO, ONE, SQRT2, SMALL
   use Types_mod,          only: Proj_type

   use Param_Setup_mod,    only: nelemIon, nelem, ldamdyn, ldyn
   use Param_Elem_mod,     only: elem
   use Param_Dam_mod,      only: dam
   use Param_Out_mod,      only: out

   use Eval_Stat_mod,      only: getDamage
   use Target_mod,         only: getDomainProperty
!
!  Default Type and Access:
!  =======================
!
   implicit none
   private
   save
!
!  Public Procedures:
!  =================
!
   public :: dam20                  ! Damage without a trajectory being followed
!            =====
   public :: dam21                  ! Damage at beginning of trajectory
!            =====
   public :: dam23                  ! Damage at end of trajectory
!            =====
   public :: edamkp                 ! Damage energy according to Kinchin-Pease
!            ======
!
!  Private Procedures:
!  ==================
!
   private :: damkp                 ! calculate damage increment according to 
!             =====                 !   modified Kinchin-Pease model
   private :: damrg                 ! calculate damage increment upon recoil
!             =====                 !    generation
   private :: damrs                 ! calculate damage increment by stopped recoil
!             =====

contains
!
!=======================================================================
!
   subroutine dam20( proj, ddam, edam )
!             =====   i     o     o
!
!     Calculate damage in a trajectory/cascade not explicitly being followed
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! starting point of trajectory
      real(REAL8), intent(out) :: ddam          ! number of Frenkel pairs
      real(REAL8), intent(out) :: edam          ! damage energy
!
!  Local Variables:
!
      logical :: lxtal
      real(REAL8) :: ddaml, ddami
      real(REAL8) :: ed(nelem)
!
!  Start of Executable Code:
!  ------------------------
!
      call getDomainProperty( proj%id, ed_=ed(:), lxtal_=lxtal )
!          =================     i       o            o

      if( proj%e < ed(proj%ielem) ) then        ! subthreshold collision
         edam = proj%e
         ddam = ZERO
      else                                      ! use Kinchin Pease model
         call damkp( proj, ddam, ddaml, ddami, edam )
!             =====   i     o      o      o     o
         if( lxtal ) then
            if( proj%origin%lattice ) then
               ddam = ddaml                     ! in crystalline layer origin
            else                                !   of primary recoil is known
               ddam = ddami
            end if
         end if
      end if

   end subroutine dam20
!
!=======================================================================
!
   subroutine dam21( proj, ddami, ddamv )
!             =====   i      o      o
!
!     Evaluate at the beginning of a trajectory
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! vacancy
      real(REAL8), intent(out) :: ddami         ! interstitial increment
      real(REAL8), intent(out) :: ddamv         ! vacancy increment
!
!  Local Variables:
!
!     None
!
!  Start of Executable Code:
!  ------------------------
!
      if( dam%ldam ) then
         call damrg( proj, ddami, ddamv )
!             =====   i      o      o
      else
         ddami = ZERO
         ddamv = ONE
      end if

    end subroutine dam21
!
!=======================================================================
!
   subroutine dam23( proj, ddami, ddamv, edam )
!             =====   i      o      o     o
!
!     Evaluate at the end of a trajectory
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! interstitial
      real(REAL8), intent(out) :: ddami         ! interstitial increment
      real(REAL8), intent(out) :: ddamv         ! vacancy increment
      real(REAL8), intent(out) :: edam          ! damage energy
!
!  Local Variables:
!
      real(REAL8) :: ddam, ddaml
      real(REAL8) :: ed(nelem)
!
!  Start of Executable Code:
!  ------------------------
!
      if( (ldyn .or. proj%ielem > nelemIon) .and. proj%origin%internal .and. dam%ldam ) then
         call getDomainProperty( proj%id, ed_=ed(:) )
!             =================     i       o
         if( proj%e < ed( proj%ielem ) ) then
            call damrs( proj, ddami, ddamv )
!                =====   i      o      o
            edam = proj%e
         else
            call damkp( proj, ddam, ddaml, ddami, edam )
!                =====   i     o      o      o     o
            ddamv = ddami                       ! vacancies generated by an existing recoil =
            ddami = ddamv + ONE                 !   additional number of Frenkel pairs when
         end if
      else
         ddami = ONE
         ddamv = ZERO
         edam = proj%e
      end if

   end subroutine dam23
!
!=======================================================================
!
   subroutine edamkp( proj, edam )
!             ======   i     o
!
!     Calculates the damage energy according to Kinchin-Pease
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! projectile
      real(REAL8), intent(out) :: edam          ! energy deposited in nuclear processes
!
!  Local Variables:
!
      logical, save :: initialized = .false.       ! flag indicating if parameters have been
                                                   !    initialized
      real(REAL8), allocatable, save :: epdfac(:)  ! (nelem)
      real(REAL8), allocatable, save :: rkd(:)     ! (nelem)
!$omp threadprivate( initialized, epdfac, rkd )

      integer(INT4) :: ielem
      real(REAL8) :: geps, epsd12, epsd, epsd34, epsd6 
!
!  Start of Executable Code:
!  ------------------------
!
!  Initialization
!
      if( .not.initialized ) then
         initialized = .true.
         allocate( epdfac( nelem ) )
         allocate( rkd( nelem ) )
         do ielem = 1, nelem
            epdfac(ielem) = 0.01014 * real(elem(ielem)%z)**(-7./3.)
            rkd(ielem) = 0.1334 * real(elem(ielem)%z)**( 2./3.) / sqrt(elem(ielem)%m)
         end do
      end if

      epsd = epdfac(proj%ielem) * proj%e         ! calculate damage energy
      epsd12 = epsd**( ONE/12 )
      epsd6 = epsd12**2
      epsd34 = epsd12*epsd6**4
      geps = epsd + 0.40244*epsd34 + 3.4008*epsd6
      edam = proj%e / ( ONE + rkd(proj%ielem)*geps )

   end subroutine edamkp
!
!=======================================================================
!
   subroutine damkp( proj, ddam, ddaml, ddami, edam )
!             =====   i     o      o      o     o
!
!     Calculates the damage increment (number of Frenkel pairs) according to
!     the modified Kinchin-Pease model considering damage recombination
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! projectile
      real(REAL8), intent(out) :: ddam          ! average damage increment if origin of primary
                                                !    recoil is unknown
      real(REAL8), intent(out) :: ddaml         ! damage increment if primary recoil was a
                                                !    lattice atom
      real(REAL8), intent(out) :: ddami         ! damage increment if primary recoil was an
                                                !    interstitial
      real(REAL8), intent(out) :: edam          ! energy deposited in nuclear processes
!
!  Local Variables:
!
      integer(INT4) :: ir
      real(REAL8) :: histv, histi, dddam, probi
      real(REAL8) :: ed(nelem), dens(nelem)
!
!  Start of Executable Code:
!  ------------------------
!
      ir = proj%id
!
!  Calculate damage without recombination
!
      call getDomainProperty( ir, ed_=ed(:), dens_=dens(:) )
!          =================  i      o            o
      if( proj%e < ed(proj%ielem) ) then
         ddam = ZERO                            ! avoid unnecessary computations
         ddaml = ZERO
         ddami = ZERO
         return
      end if

      call edamkp( proj, edam )
!          ======   i     o

      if( edam < ed(proj%ielem) ) then   ! calculate damage increment
         ddam = ZERO
         ddaml = ZERO
         ddami = ZERO
         return
      elseif( edam < 2.5*ed(proj%ielem) ) then
         ddam = ONE
      else
         ddam = edam/( 2.5*ed(proj%ielem) )
      end if
!
!  Consider damage recombination and reduction by multiple recoiling 
!
                                                ! determine local damage concentration
      if( ldamdyn ) then
         call getDamage( proj%pos(:), proj%ielem, histi, histv )
!             =========      i            i         o      o
      else
         histi = ZERO
      end if
      probi = histi / max( histi, dens(proj%ielem), SMALL )
                                                ! average damage with unknown origin of the
      ddam = ddam * ( (ONE + dam%frec -  &     !    primary recoil
                       (ONE-dam%fracrg + dam%fracrg*dam%frec) * probi) *  &
                       (ONE-dam%facsat*histi) - ONE )
      dddam = (ONE-dam%fracrg + dam%fracrg*dam%frec) * (ONE - dam%facsat*histi)

      ddami = ddam - (ONE-probi)*dddam          ! damage with known origin of the primary recoil
      ddaml = ddam + probi*dddam

      if( histi > dam%damamo ) then             ! to preliminarily cure a problem when frec<1
         ddam = max( ddam, ZERO )               !    and damamo<dens
         ddami = max( ddami, ZERO )
         ddaml = max( ddaml, ZERO )
      end if

   end subroutine damkp
!
!=======================================================================
!
   subroutine damrg( proj, ddami, ddamv )
!             =====   i      o      o
!
!     Calculates the damage increment when a recoil is generated
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! projectile (recoil)
      real(REAL8), intent(out) :: ddami         ! interstitial increment 
      real(REAL8), intent(out) :: ddamv         ! vacancy increment 
!
!  Local Variables:
!
      logical :: lxtal
      integer(INT4) :: ir
      real(REAL8) :: ddamvl, probl, probi, histi, histv, dens(nelem)
!
!  Start of Executable Code:
!  ------------------------
!
      ir = proj%id
      call getDomainProperty( proj%id, lxtal_=lxtal, dens_=dens(:) )
!          =================     i          o              o
                                                ! in a crystalline region the origin of the
      if( lxtal ) then                          !   recoil is known and damage recombination
                                                !   is taken into account
                                        
         if( proj%origin%lattice ) then         ! recoil originates from a lattice site
                         
            if( ldamdyn ) then
               call getDamage( proj%pos(:), proj%ielem, histi, histv )
!                   =========      i            i         o      o
            else
               histi = ZERO
            end if

            ddamv = (ONE-dam%fracrg + dam%fracrg*dam%frec) * (ONE - dam%facsat*histi)
            ddami = ddamv-ONE

         else                                   ! recoil was an interstitial

            ddamv = ZERO
            ddami = -ONE

         end if
                                                ! in an amorphous region the origin of the
      else                                      !   recoil is unknown, so we take an average
                                        
         if( ldamdyn ) then
            call getDamage( proj%pos(:), proj%ielem, histi, histv )
!                =========      i            i         o      o
         else
            histi = ZERO
            histv = ZERO
         end if

         if( histv >= dens(proj%ielem) ) then   ! just in case ...
            probl = ZERO
            probi = ONE
         else if( histi <= ZERO ) then
            probl = ONE
            probi = ZERO
         else
            probl = ( dens(proj%ielem) - histv ) / ( dens(proj%ielem) - histv + histi )
            probi = ONE - probl
         end if

         ddamvl = (ONE-dam%fracrg + dam%fracrg*dam%frec) * (ONE - dam%facsat*histi)
         ddamv = ddamvl * probl
         ddami = (ddamvl-ONE) * probl - probi

      end if

   end subroutine damrg
!
!=======================================================================
!
   subroutine damrs( proj, ddami, ddamv )
!             =====   i      o      o
!
!     Calculates the damage increment when a projectile is stopped
!
!  Arguments:
!
      type(Proj_type), intent(in) :: proj       ! projectile
      real(REAL8), intent(out) :: ddami         ! interstitial increment 
      real(REAL8), intent(out) :: ddamv         ! vacancy increment 
!
!  Local Variables:
!
      real(REAL8) :: histv, histi
!
!  Start of Executable Code:
!  ------------------------
!
      if( ldamdyn ) then
         call getDamage( proj%pos(:), proj%ielem, histi, histv )
!             =========      i            i         o      o
      else
         histv = ZERO
      end if

      ddami = ( dam%fracrg + (ONE-dam%fracrg)*dam%frec ) * ( ONE - dam%facsat*histv )
      ddamv = ddami - ONE

   end subroutine damrs
!
!=======================================================================
!
end module Eval_Dam_mod
