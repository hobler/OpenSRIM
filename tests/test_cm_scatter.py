@pytest.mark.usefixtures("build_and_run_f90")
def test_scattering_at_and_beyond_cutoff_python_numba_fortran():
    """Check vanishing NLHlin scattering at and beyond the cutoff.

    The test compares the scattering angles and time integrals computed by the Python, Numba, and 
    Fortran backends for the NLHlin screening model at and beyond the cutoff radius. It uses a set of 
    predefined energy values and impact parameters to evaluate the scattering quantities and checks 
    for consistency across all three implementations. The test will fail if any of the backends produce 
    results that do not match the expected values within the specified tolerances, or if any of the backends 
    return non-zero scattering quantities at or beyond the cutoff radius.

    the cutoff radius is the maximum radius beyond which the NLHlin screening model predicts no scattering. 
    The test ensures that all backends correctly implement this behavior and return zero scattering quantities at and beyond the cutoff radius.

    Args:
        None
    """

    # load the screening function and potential coefficients for the NLHlin model
    screen = get_python_screen_fun("NLHlin")
    pot_model, pot_coefs = build_numba_potential("NLHlin")
    assert_arrays_equal(screen.rmax, pot_coefs.rmax, rtol=0, atol=1e-14)

    # define the impact parameter values to test at and beyond the cutoff radius
    p_values = np.array([screen.rmax, np.nextafter(screen.rmax, np.inf), 30.0])
    summaries, failures = {}, []

    # iterate over the predefined energy values and calculate the scattering angles and time integrals 
    # for the specified impact parameters using both Python and Numba backends
    for e in E_VALUES_SIN:
        for p in p_values:
            r0, count = cm_scatter_nb.get_apsis(e, p, pot_model, pot_coefs)
            assert r0 == p and count == 0
        python, numba = calculate_scatter(e, p_values, screen, pot_model, pot_coefs, grid_name="cutoff")

        # load the Fortran reference data for scattering angles and time integrals at the specified energy and impact parameters
        data = load_fortran_data(reference_filename('scatter', dict(model="NLHlin", z1=5, z2=14, e=e, n_absc=4), norm='native', grid_name='cutoff', extension='txt'), p_values, columns=3)
        for index, quantity in enumerate(("theta", "tau")):
            values = dict(Python=python[index], Numba=numba[index], Fortran=data[:, index+1])

            # compare the scattering angles and time integrals computed by the Python, Numba, and Fortran backends for the 
            # specified energy and impact parameters
            compare_three_way(summaries, failures, values, p_values, f"e={e}", "boundary", tolerances=TOLERANCES,
                              prefix=f"{quantity}: ")

            # check that all backends return zero scattering quantities at and beyond the cutoff radius for the specified energy and impact parameters
            for label, result in values.items():
                try:
                    assert_arrays_equal(np.zeros_like(p_values), result, rtol=0, atol=0)
                except AssertionError as exc:
                    failures.append(f"{label} {quantity} at cutoff: {exc}")

    # finalize the comparison and report any failures encountered during the test
    finish_comparison("NLHlin cutoff", summaries, failures)


