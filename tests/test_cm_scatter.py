@pytest.mark.parametrize("model", all_models())
@pytest.mark.usefixtures("build_and_run_f90")
def test_tau_error_data_python_numba_fortran(model):
    """Compare native time integrals and report a finer Python calculation.

    The test compares the time integrals (tau) computed by the Python, Numba, and Fortran 
    backends for the specified screening model across a set of predefined energy values and 
    corresponding impact parameters. It uses a finer Python calculation as a diagnostic baseline 
    to assess the accuracy of the native time integrals computed by the Numba and Fortran backends. 
    The test will fail if any of the backends produce results that do not match the expected values within the specified tolerances.

    Args:
        model (str): The screening model to test.
    """

    # load the screening function and potential coefficients for the specified model
    screen = get_python_screen_fun(model)
    pot_model, pot_coefs = build_numba_potential(model)
    summaries, failures = {}, []

    # iterate over the predefined energy values and corresponding impact parameters 
    # to calculate the time integrals using both Python and Numba backends
    for e, p_values in zip(E_VALUES_ERROR, P_VALUES_ERROR):

        # calculate the time integrals using a finer Python calculation as a diagnostic baseline
        _, tau_ref = calculate_scatter_python(e, p_values, screen, n_absc=32, grid_name="error")
        (_, tau_py), (_, tau_nb) = calculate_scatter(e, p_values, screen, pot_model, pot_coefs, grid_name="error")

        # load the Fortran reference data for time integrals at the specified energy and impact parameters
        data = load_fortran_data(reference_filename('scatter', dict(model=model, z1=5, z2=14, e=e, n_absc=4), norm='native', grid_name='error', extension='txt'), p_values, columns=3)

        # ensure that the reference time integrals are finite for comparison
        assert np.all(np.isfinite(tau_ref))
        values = dict(Python=tau_py, Numba=tau_nb, Fortran=data[:, 2])

        # compare the time integrals computed by the Python, Numba, and Fortran backends for the specified energy and impact parameters
        compare_three_way(summaries, failures, values, p_values, f"e={e}", "tau", tolerances=TOLERANCES)

        # record the maximum error of each backend against the finer Python calculation as a diagnostic baseline
        for label, result in values.items():
            record_max_error(summaries, f"{label} vs Python 32-point (diagnostic)",
                             result, tau_ref, p_values, context=f"e={e}",
                             labels=(label, "Python 32-point"))

    # finalize the comparison and report any failures encountered during the test
    finish_comparison(f"{model} tau and 32-point diagnostic", summaries, failures)


