def test_small_impact_and_inside_cutoff_python_numba_fortran(model, extended_fortran):
    """Check small positive impact parameters and the approach to the NLHlin cutoff.

    The test compares the scattering angles (theta) and time integrals (tau) computed by the Python, Numba, and
    Fortran backends for the specified screening model at small positive impact parameters and near the NLHlin cutoff.
    It uses a set of predefined energy values and corresponding impact parameters to evaluate the scattering
    quantities and checks for consistency across all three implementations. The test will fail if any of the
    backends produce results that do not match the expected values within the specified tolerances, or
    if any of the backends return non-finite scattering quantities at small impact parameters or near the cutoff.

    Args:
        model (str): The screening model to test.
        extended_fortran: The extended Fortran data for the test.
    """

    # Initialize the screening parameters and grid for the specified model and element pair (5, 14)
    screen, coefs = pair_inputs(model, 5, 14)
    energies, points = extended_grid('boundary', model, screen.rmax)

    # Load the Fortran reference data for scattering angles and time integrals at the specified energy and impact parameters for the given element pair (5, 14)
    fortran = extended_outputs(extended_fortran, 'boundary', model, (5, 14), 4, energies, points)
    summaries, failures = {}, []

    # iterate over the predefined energy values and corresponding impact parameters to calculate
    # the scattering angles and time integrals using both Python and Numba backends
    for i, e in enumerate(energies):
        for p in points:
            r0, iterations = cm_scatter_nb.get_apsis(e, p, model, coefs)

            # check that the calculated apsis is finite and within the expected range, and that the number of iterations is reasonable
            assert np.isfinite(r0) and p <= r0 <= screen.rmax
            assert 0 <= iterations <= 100
        python, numba = calculate_scatter(e, points, screen, model, coefs, grid_name="boundary")

        # compare the scattering angles and time integrals computed by the Python, Numba, and
        # Fortran backends for the specified energy and impact parameters for the given element pair (5, 14)
        for j, quantity in enumerate(('theta', 'tau')):
            values = dict(Python=python[j], Numba=numba[j], Fortran=fortran[i, j])

            # compare the scattering angles and time integrals computed by the Python, Numba, and 
            # Fortran backends for the specified energy and impact parameters
            compare_three_way(summaries, failures, values, points, f'e={e}', quantity,
                              tolerances=TOLERANCES, prefix=f'{quantity}: ')

        # check that all backends return finite scattering angles within the expected range [0, pi] for the specified energy and impact parameters
        for label, angles in (('Python', python[0]), ('Numba', numba[0]), ('Fortran', fortran[i, 0])):
            if not np.all((angles >= -1e-11) & (angles <= np.pi+1e-11)):
                failures.append(f'{label}, e={e}: angle outside [0, pi] or nonfinite')

    # finalize the comparison and report any failures encountered during the test
    finish_comparison(f'{model} small p and approach to cutoff', summaries, failures)
